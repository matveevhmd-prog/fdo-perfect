def rows():
    out = {}
    for l in RM.splitlines():
        m = re.match(r"^\| (W\d+\.\d+)[  ]([^|]*)\|(.*)\|\s*$", l)
        if not m:
            continue
        cells = [c.strip() for c in m.group(3).split("|")]
        st = cells[-1] if cells else ""
        found = {("✅" if x == "🟢" else x) for x in ("✅", "🟢", "🟡", "⬜") if x in st}
        if not found:
            sym = "⬜"
        elif len(found) == 1:
            sym = next(iter(found))
        else:
            sym = "🟡"  # у клітинці змішані статуси (частково зроблено)
        blocked = "⛔" in st or "⛔" in m.group(2)
        out[m.group(1)] = (re.sub(r"\s+", " ", m.group(2)).strip(), sym, blocked, re.sub(r"\s+", " ", st))
    return out


def criteria():
    d = {}
    for m in re.finditer(r"^\| (R-\d+) \| (.+?) \|", RM, re.M):
        d[m.group(1)] = re.sub(r"\*\*|`", "", m.group(2))
    return d


def open_ods():
    res = []
    for m in re.finditer(r"^\| (OD-\d+) \|(.*)$", RM, re.M):
        row = m.group(2)
        if "Закрито" in row or "~~" in row:
            continue
        title = re.sub(r"\s+", " ", row.split("|")[0]).strip()
        res.append((m.group(1), title[:150]))
    return res


def wd_rows():
    res = []
    for m in re.finditer(r"^\| (WD\.\d+) (.*?) \|", RM, re.M):
        res.append((m.group(1), re.sub(r"\s+", " ", m.group(2))[:120]))
    return res


